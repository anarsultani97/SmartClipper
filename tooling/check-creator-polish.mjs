// Opt-in browser/media acceptance against the running API + worker. No unit suite.
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';

const origin = 'http://127.0.0.1:5173';
assert((await fetch(origin + '/api/v1/health')).ok);
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin);
  await page.getByRole('button', { name: 'Choose video' }).waitFor();
  const cdp = await context.newCDPSession(page);
  await cdp.send('Network.enable');
  await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 20, downloadThroughput: 1024 * 1024, uploadThroughput: 16000 });
  await page.getByLabel('Import video file').setInputFiles('.cache/creator-public.mp4');
  await page.getByRole('progressbar', { name: 'Uploading your video' }).waitFor();
  assert((await page.getByRole('progressbar', { name: 'Uploading your video' }).getAttribute('aria-valuenow')) !== '100');
  await page.screenshot({ path: '.cache/creator-upload.png', fullPage: true });
  await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
  await page.waitForURL(/\/projects\/[^/]+$/);
  const projectPath = new URL(page.url()).pathname;
  const projectId = projectPath.split('/').at(-1);
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent.includes('Generate shorts') && !b.disabled), undefined, { timeout: 60000 });
  await page.getByLabel('Video language').selectOption('en');
  await page.getByLabel('Number of suggestions').selectOption('1');
  await page.getByText('Speech accuracy & cover framing', { exact: true }).click();
  await page.getByLabel('Speech processing').selectOption('fast');
  const began = Date.now();
  await page.getByRole('button', { name: 'Generate shorts' }).click();
  await page.locator('.generation-stage .ring-meter').waitFor();
  await page.screenshot({ path: '.cache/creator-generation.png', fullPage: true });
  await page.getByText('THE STORY IN THIS CUT', { exact: true }).waitFor({ timeout: 120000 });
  const firstShortSeconds = (Date.now() - began) / 1000;
  await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
  await page.locator('video').evaluate(v => { v.currentTime = 2; return v.play(); });
  await page.locator('.styled-caption .spoken').first().waitFor();
  await page.locator('video').evaluate(v => v.pause());
  await page.getByLabel('Caption style').selectOption('karaoke');
  await page.getByLabel('Caption position').selectOption('middle');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await page.getByRole('button', { name: 'Saved', exact: true }).waitFor();
  await page.getByText('Review & correct transcript', { exact: true }).click();
  const field = page.locator('.caption-editor textarea').first();
  await field.waitFor();
  const corrected = 'A clear idea deserves a clear caption.';
  await field.fill(corrected);
  const savedCaption = page.waitForResponse(r => r.url().endsWith('/captions') && r.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save transcript', exact: true }).click();
  // Caption saves remount the editor at its new revision; confirm persistence from the API.
  assert.equal((await savedCaption).status(), 200);
  await page.reload();
  await page.getByText('THE STORY IN THIS CUT', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Caption style').inputValue(), 'karaoke');
  assert.equal(await page.getByLabel('Caption position').inputValue(), 'middle');
  await page.getByText('Review & correct transcript', { exact: true }).click();
  assert.equal(await page.locator('.caption-editor textarea').first().inputValue(), corrected);
  await page.screenshot({ path: '.cache/creator-editor.png', fullPage: true });
  await page.getByRole('switch').click();
  await page.getByRole('button', { name: 'Add styled subtitles', exact: true }).click();
  await page.getByText('Captions on', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Original video & preferences' }).click();
  await page.getByRole('button', { name: 'View shorts' }).click();
  await page.getByText('THE STORY IN THIS CUT', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Original video & preferences' }).click();
  await page.getByRole('main').getByRole('button', { name: 'My videos', exact: true }).click();
  await page.locator('.library-actions').getByRole('button', { name: 'View shorts' }).first().click();
  await page.getByText('THE STORY IN THIS CUT', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: '.cache/creator-mobile.png', fullPage: true });
  assert.equal(errors.length, 0, errors.join('\n'));
  await writeFile('.cache/creator-browser-results.json', JSON.stringify({ projectId, firstShortSeconds, checks: ['upload ring', 'generation progress', 'word highlighting', 'caption styles and corrections', 'add subtitles', 'return to shorts', 'mobile layout', 'no browser exceptions'] }, null, 2));
  console.log(`Creator browser/media acceptance passed. First 30-second-source short: ${firstShortSeconds.toFixed(2)}s.`);
} finally { await browser.close(); }
